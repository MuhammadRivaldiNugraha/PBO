public class OperatorIncrement {
    public static void main(String[] args) {
        int a = 5;
        int b = 5;
        System.out.println("a++ = " + a++);
        System.out.println("a sekarang = " + a);

        System.out.println("++b = " + ++b);
        System.out.println("b sekarang = " + b);
    }
}
